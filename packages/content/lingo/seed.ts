type Seed = Omit<LexiconRow, 'active' | '_status' | 'locale'> & { readonly active?: boolean };

function line(key: string, speciesId: string, stage: LexiconRow['stage'], occasion: string, text: string, sourceBasis: string, meaning: string): Seed {
  return {
    key: `mon-line.${speciesId}.${stage?.toLowerCase()}.${key}`,
    entryType: 'call_response',
    category: 'mon-line',
    canonicalText: text,
    triggerText: occasion,
    responseText: text,
    speciesId,
    bloodlineId: RATTI,
    stage,
    meaning,
    activationPolicy: `Spoken by the Caller’s own Mon at the ${stage} stage when the occasion is “${occasion}”. ${NEVER_INFER}`,
    sourceBasis,
  };
}

function rule(key: string, subcategory: string, text: string, meaning: string, sourceBasis: string, extra: Partial<Seed> = {}): Seed {
  return {
    key: `voice-rule.${key}`,
    entryType: 'style_rule',
    category: 'voice-rule',
    subcategory,
    canonicalText: text,
    meaning,
    activationPolicy: 'Guidance for whoever writes the Mon’s lines (the Agent Skill, the companion prompt). Never spoken as written.',
    sourceBasis,
    ...extra,
  };
}

function palette(key: string, word: string, meaning: string, policy: string): Seed {
  return {
    key: `word-palette.hood-ratti.${key}`,
    entryType: 'lexicon',
    category: 'word-palette',
    subcategory: 'hood-ratti',
    canonicalText: word,
    bloodlineId: RATTI,
    register: 'African American English, NYC',
    meaning,
    activationPolicy: `${policy} One or two palette words per line at most, never stacked; standard spelling. Character lines only, never the plain voice, never a line that carries a care fact.`,
    avoidWhen: 'Any line that carries a care fact; the plain voice; a refusal.',
    sourceBasis: `${SKILL} §Hood Ratti line › Word palette (owner-approved 2026-10-23)`,
  };
}

function direction(key: string, sortOrder: number, tag: string, keywords: readonly string[]): Seed {
  return {
    key: `stage-direction.${key}`,
    entryType: 'pronunciation_rule',
    category: 'stage-direction',
    canonicalText: key.replace(/-/g, ' '),
    spokenForm: tag,
    variants: keywords.join('|'),
    sortOrder,
    meaning: `A *stage direction* whose words contain any of these keywords is performed as the audio tag ${tag}.`,
    activationPolicy: 'The voice turns a matching *direction* into this tag; the first match by sort order wins. A direction with no match is dropped, never read out.',
    sourceBasis: 'packages/content/voices.ts STAGE_DIRECTION_TAGS (2026-10-23); ElevenLabs v3/v4 audio tags',
  };
}

