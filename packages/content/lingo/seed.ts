/**
 * The seed for the Mon's lines and lingo in Payload, and the offline fallback.
 *
 * Payload is the source of truth. Migration `20261028_200000_mon_lingo_seed`
 * (packages/payload/src/migrations) writes exactly these rows into `language-lexicon` and this voice data into
 * the `mon-voices` global; after that, Mike edits them in the admin and
 * `GET /v1/mon-lingo` serves what is published. Code that has no server
 * (tests, an app with no network yet) uses `FALLBACK_MON_LINGO`, which is
 * built from this same seed by the same function the server uses
 * (`monLingoFromRows`), so the fallback and a freshly seeded Payload plan
 * every line identically.
 *
 * Do not edit this file to change what the Mon says: edit Payload. A change
 * here does not reach a database that already ran the seed migration, and
 * packages/payload/src/__tests__/mon-lingo-seed.test.ts pins this seed's hash
 * to the one that migration recorded. A new seed needs a new migration.
 *
 * Sources: the rows citing SKILL quote skills/nyc-mon-companion/SKILL.md
 * verbatim (owner decisions of 2026-10-23), and the rows citing only the
 * brief quote docs/alexa-plus-brief.md §Character voice rules verbatim;
 * test/skill-drift.test.ts checks both. The voice numbers, stage directions and the Caller pronunciation
 * were packages/content/voices.ts on 2026-10-28; the Squeaklet lines were
 * packages/content/mon-lines.ts (OPEN_QUESTIONS Q32).
 */

