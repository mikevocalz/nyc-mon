#!/usr/bin/env node
// Generates this project's .rml inputs by merging the three sibling arcade
// projects — left-stick, right-six, start-stop — into one Rive document with
// five artboards: LeftStick, Thumbpad, RightSix, ArcadeButton and StartStop.
//
// Each source document uses the same `0:` object-id space, so every `0:N`
// token is renumbered to this file's own document prefix (`1:`, `2:`, `3:`).
// That includes ids inside dash-separated lists such as
// sourcePathIds="0:40-0:45-0:53" — an earlier naive merge that only rewrote
// whole attribute values left those list members pointing at document 0 and
// `rive inspect` reported them as unresolved bind paths.
//
// The Space Grotesk font is declared by both right-six and start-stop. The
// merged document keeps a single FontAsset: start-stop's duplicate element is
// dropped and every reference to its id is rewritten to right-six's.
//
// Artboards get explicit stage x/y so the merged file does not warn about
// artboards overlapping at the origin.
//
// Usage: node merge.mjs [--check]
//   (no flag)  writes stick.rml, cluster.rml and pill.rml
//   --check    regenerates and exits non-zero if the committed files differ
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));

const SOURCES = [
  { doc: '1', src: '../left-stick/scene.rml', out: 'stick.rml' },
  { doc: '2', src: '../right-six/scene.rml', out: 'cluster.rml' },
  { doc: '3', src: '../start-stop/scene.rml', out: 'pill.rml' },
];

// An `0:N` id that is not already a suffix of another document id. The
// lookbehind keeps `10:` and `1:` tokens out; the `-0:45` members of a
// sourcePathIds list still match because `-` is not in the excluded set.
const DOC_ID = /(?<![0-9A-Za-z:])0:(\d+)/g;

// Horizontal gap between artboards on the merged file's stage.
const STAGE_GAP = 60;

export function renumber(text, doc) {
  return text.replace(DOC_ID, `${doc}:$1`);
}

// Shifts every <Artboard> in this document right by `offset` so the merged
// stage keeps each source's authored layout but the documents no longer
// overlap at the origin. An artboard with no x/y sits at the doc's origin.
// Returns the new text plus the stage x just past this document's right edge.
export function stageArtboards(text, offset) {
  let right = offset;
  const out = text.replace(/<Artboard\b[^>]*>/g, (tag) => {
    const width = Number(/\bwidth="([\d.]+)"/.exec(tag)?.[1] ?? 0);
    const base = /\bx="([-\d.]+)"/.exec(tag);
    const x = (base ? Number(base[1]) : 0) + offset;
    right = Math.max(right, x + width);
    if (base) return tag.replace(base[0], `x="${x}"`);
    return tag.replace(/<Artboard\b/, `<Artboard x="${x}" y="0"`);
  });
  return { text: out, right };
}

// Called on renumbered text: ids already carry this file's document prefix.
function fontAssets(text) {
  return [...text.matchAll(/<FontAsset\b[^>]*?\/>/g)].map((m) => ({
    file: /file="([^"]+)"/.exec(m[0])?.[1],
    num: /id="\d+:(\d+)"/.exec(m[0])?.[1],
  }));
}

const generatedNote = (s) =>
  `    <!-- GENERATED by merge.mjs from ${s.src} (object ids renumbered 0: -> ${s.doc}:).\n` +
  `         Edit the source project, then run ./build.sh here. Do not hand-edit this file. -->\n`;

export function generate() {
  const fonts = new Map(); // asset file path -> canonical `doc:num` id
  const cursor = { at: 0 };
  return SOURCES.map((s) => {
    let text = renumber(readFileSync(join(HERE, s.src), 'utf8'), s.doc);
    for (const font of fontAssets(text)) {
      const id = `${s.doc}:${font.num}`;
      const canonical = fonts.get(font.file);
      if (!canonical) {
        fonts.set(font.file, id);
      } else {
        // Every reference to the duplicate font now names the canonical one,
        // then the duplicate <FontAsset> element itself is dropped.
        text = text.replace(new RegExp(`(?<![0-9:])${id}(?!\\d)`, 'g'), canonical);
        text = text
          .split('\n')
          .filter((line) => !(line.includes('<FontAsset') && line.includes(`file="${font.file}"`)))
          .join('\n');
      }
    }
    const staged = stageArtboards(text, cursor.at);
    text = staged.text;
    cursor.at = staged.right + STAGE_GAP;
    text = text.replace(/<Rive\b[^>]*>\n/, (m) => m + generatedNote(s));
    return { out: s.out, text };
  });
}

const checkOnly = process.argv.includes('--check');
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  let drift = 0;
  for (const { out, text } of generate()) {
    const path = join(HERE, out);
    if (checkOnly) {
      let current = null;
      try {
        current = readFileSync(path, 'utf8');
      } catch { /* missing counts as drift */ }
      if (current !== text) {
        console.error(`merge: ${out} is stale — run \`node merge.mjs\` (or ./build.sh) to regenerate`);
        drift = 1;
      }
    } else {
      writeFileSync(path, text);
      console.log(`merge: wrote ${out} (${text.length} bytes)`);
    }
  }
  process.exit(drift);
}
