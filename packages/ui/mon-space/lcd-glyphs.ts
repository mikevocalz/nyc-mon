/** Rows for `ch`; anything the face lacks draws as "?". */
export function fontGlyph(ch: string): readonly number[] {
  return F[ch] ?? F['?']!;
}

/** True when the face has `ch` (tests check the copy only uses drawn characters). */
export function hasGlyph(ch: string): boolean {
  return ch in F;
}

