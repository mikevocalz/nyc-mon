// Regenerates packages/app/features/game/world/cell-source/data/vd-cells-manifest.ts: the trusted manifest the
// on-demand cell source pins every download against (cell-source.ts): sha256 + byteLength per cell, and `bundled`
// where a copy also ships in the app as a Metro asset (first-launch offline).
//
//   structures/<cx>_<cz>  lane C's structure cells (vd-port/furniture/cells), all bundled;
//   near/<cx>_<cz>        lane A's near level (vd-port/blocks/data/near), all bundled;
//   lite/<cx>_<cz>        lane A's lite near level (vd-port/blocks/data/lite), all bundled;
//   far/<L<lv>_<i>_<j>.bin> the far tier's L4/L6 chunks (vd-port/far-tier): only the home subset (manifest `home`,
//     the chunks write-far.mjs copied into far-tier/data/chunks) is bundled; the rest stream on demand;
//   far/landmarks_l6.bin  the landmark silhouettes: one pinned file, fetched on demand, never bundled.
//
//   node tooling/city/vd-port/write-cells-manifest.mjs
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const ROOT = join(HERE, '..', '..', '..');
const APP = join(ROOT, 'packages/app/features/game');
const FAR_CACHE = join(HERE, '..', '.cache', 'vd-lod16');
const OUT = join(APP, 'world/cell-source/data/vd-cells-manifest.ts');

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

const cells = {};
let bundledBytes = 0;
const add = (key, file, bundled) => {
  const buf = readFileSync(file);
  cells[key] = { path: key.endsWith('.bin') ? key : `${key}.bin`, sha256: sha256(buf), bytes: buf.length, bundled };
  if (bundled) bundledBytes += buf.length;
};

for (const [level, dir] of [
  ['structures', join(APP, 'world/vd-port/furniture/cells')],
  ['near', join(APP, 'world/vd-port/blocks/data/near')],
  ['lite', join(APP, 'world/vd-port/blocks/data/lite')],
]) {
  for (const f of readdirSync(dir).filter((n) => n.endsWith('.bin')).sort()) {
    add(`${level}/${f.slice(0, -4)}`, join(dir, f), true);
  }
}

// The far tier: chunk list and the home flags come from the generated VD_FAR manifest (write-far.mjs run first).
const farManifestTs = readFileSync(join(APP, 'world/vd-port/far-tier/data/manifest.ts'), 'utf8');
const VD_FAR = JSON.parse(farManifestTs.slice(farManifestTs.indexOf('{'), farManifestTs.lastIndexOf('}') + 1));
for (const c of VD_FAR.chunks) {
  add(`far/${c.f}`, join(FAR_CACHE, c.f), c.home === true);
}
if (VD_FAR.landmarks) {
  add(`far/${VD_FAR.landmarks.f}`, join(FAR_CACHE, VD_FAR.landmarks.f), false);
}

const lines = Object.keys(cells).sort().map((k) => {
  const c = cells[k];
  return `    '${k}': { path: '${c.path}', sha256: '${c.sha256}', bytes: ${c.bytes}, bundled: ${c.bundled} },`;
});
const ts = `// GENERATED by tooling/city/vd-port/write-cells-manifest.mjs (sha256 + byteLength of every servable cell). Do not edit by hand.
// The trusted manifest the on-demand source pins every download against (cell-source.ts).
import type { CellManifest } from '../types.ts';

export const VD_CELL_MANIFEST: CellManifest = {
  version: 1,
  cells: {
${lines.join('\n')}
  },
};
`;
await writeFile(OUT, ts);
console.log(`wrote ${lines.length} cells (${(bundledBytes / 1e6).toFixed(1)} MB bundled) to ${OUT}`);
