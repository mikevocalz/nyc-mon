import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL } from 'node:url';
import { canonicalSurfaceJSON } from './surface-registry.mjs';

const sha = bytes => createHash('sha256').update(bytes).digest('hex');
const positive = value => Number.isSafeInteger(value) && value > 0;
const safeFile = name => typeof name === 'string' && /^[a-zA-Z0-9_-]+\.bin$/.test(name);

/** Publish authenticated source packs as static Metro assets. Admission is an explicit input, never inferred from total bank size. */
export async function writeSurfaceAssets({ geometryDir, bankDir, outputDir, admission }) {
  if (!positive(admission?.materialBytes) || !['geometryBytes', 'cellDraws', 'triangles'].every(key => positive(admission?.budget?.[key])) ||
      (admission.budget.vertices !== undefined && !positive(admission.budget.vertices)) ||
      !['geometryBytes','cellDraws','triangles'].every(key=>positive(admission?.legacyMinimum?.[key]))) throw new Error('Explicit positive source admission budgets are required');
  const registryBytes = await readFile(join(geometryDir, 'registry.json'));
  const geometryBytes = await readFile(join(geometryDir, 'manifest.json'));
  const bankBytes = await readFile(join(bankDir, 'manifest.json'));
  const registry = JSON.parse(registryBytes), geometry = JSON.parse(geometryBytes), bank = JSON.parse(bankBytes);
  if (!/^[a-f0-9]{64}$/.test(registry.sha256) || !registry.coverage?.complete || bank.complete !== true || geometry.complete !== true || !Array.isArray(geometry.cells) || !geometry.cells.length) throw new Error('Incomplete authenticated source assets');
  const {sha256:registrySha,...registryBody}=registry;
  if(sha(Buffer.from(canonicalSurfaceJSON(registryBody)))!==registrySha)throw new Error('Source registry hash mismatch');
  const pages = new Map(), cells = new Map();
  for (const page of bank.pages) {
    const file = page.storage?.file ?? `${page.sha256}.bin`;
    if (!Number.isSafeInteger(page.id) || page.id<0 || !safeFile(file) || pages.has(page.id)) throw new Error('Invalid or duplicate source page asset');
    const bytes = await readFile(join(bankDir, file));
    if (bytes.length !== (page.storage?.fileBytes ?? page.sourceBytes) || sha(bytes) !== (page.storage?.sha256 ?? page.sha256)) throw new Error(`Source page asset hash mismatch: ${page.id}`);
    pages.set(page.id, { file });
  }
  for (const cell of geometry.cells) {
    const file = `${cell.key}.bin`;
    if (!safeFile(file) || cells.has(cell.key) || cell.surface?.sha256 !== registry.sha256) throw new Error('Invalid or mismatched source cell asset');
    const bytes = await readFile(join(geometryDir, file));
    if (bytes.length !== cell.fileBytes || sha(bytes) !== cell.sha256) throw new Error(`Source cell asset hash mismatch: ${cell.key}`);
    cells.set(cell.key, { file });
  }
  await mkdir(join(outputDir, 'pages'), { recursive: true });
  await mkdir(join(outputDir, 'cells'), { recursive: true });
  // Copy only after every input validates. A failed validation cannot publish a partial new manifest/entry.
  for (const { file } of pages.values()) await copyFile(join(bankDir, file), join(outputDir, 'pages', file));
  for (const { file } of cells.values()) await copyFile(join(geometryDir, file), join(outputDir, 'cells', file));
  await writeFile(join(outputDir, 'registry.json'), registryBytes);
  await writeFile(join(outputDir, 'manifest.json'), geometryBytes);
  await writeFile(join(outputDir, 'pages', 'manifest.json'), bankBytes);
  const source = `// Generated by tooling/city/vd-port/write-surface-assets.mjs. CPU metadata only; bytes load on demand.
/* eslint-disable @typescript-eslint/no-require-imports */
import type { SourceBlockAssets } from '../surface-part.ts';
const registry = require('./registry.json');
const manifest = require('./pages/manifest.json');
const cells = require('./manifest.json').cells;
const pages: Readonly<Record<number, number>> = {
${[...pages].map(([id, page]) => `  ${JSON.stringify(id)}: require(${JSON.stringify(`./pages/${page.file}`)}),`).join('\n')}
};
const geometry: Readonly<Record<string, number>> = {
${[...cells].map(([key, cell]) => `  ${JSON.stringify(key)}: require(${JSON.stringify(`./cells/${cell.file}`)}),`).join('\n')}
};
export const VD_SOURCE_REGISTRY_SHA256 = ${JSON.stringify(registry.sha256)};
export function createVdBlockSurfaceAssets(fetchBytes: (source: number) => Promise<ArrayBuffer>): SourceBlockAssets {
  const read = async (id: number | undefined, signal?: AbortSignal) => {
    if (id === undefined) throw new Error('Missing bundled authored source asset');
    const check = () => { if (signal?.aborted) throw Object.assign(new Error('Source asset read aborted'), { name: 'AbortError' }); };
    check(); const bytes = await fetchBytes(id); check(); return new Uint8Array(bytes);
  };
  return { registry, manifest, cells, expectedSha256: VD_SOURCE_REGISTRY_SHA256,
    materialBytes: ${admission.materialBytes}, budget: ${JSON.stringify(admission.budget)},
    admission: { legacyMinimum: ${JSON.stringify(admission.legacyMinimum)} },
    readPage: (page, signal) => read(pages[page.id], signal),
    readCell: (cell, signal) => read(geometry[cell.key], signal),
  };
}
`;
  await writeFile(join(outputDir, 'assets.ts'), source);
  return { registrySha256: registry.sha256, pages: pages.size, cells: cells.size };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const [geometryDir, bankDir, outputDir, admissionPath] = process.argv.slice(2);
  if (!admissionPath) throw new Error('Usage: write-surface-assets.mjs geometryDir bankDir outputDir admission.json');
  console.log(JSON.stringify(await writeSurfaceAssets({ geometryDir, bankDir, outputDir, admission: JSON.parse(await readFile(admissionPath, 'utf8')) })));
}
