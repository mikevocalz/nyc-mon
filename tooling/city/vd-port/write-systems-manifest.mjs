// Runs the five Phase 4 emitters and pins every pack they wrote into the cell-source manifest — the
// write-cells-manifest.mjs conventions: sha256 + byteLength per cell, `bundled` where a copy ships in the
// app, keys `<kind>/<cx>_<cz>`. Output:
//
//   packages/app/features/game/world/cell-source/data/vd-systems-manifest.ts  (VD_SYSTEM_MANIFEST)
//   packages/app/features/game/world/vd-port/systems/data/assets.ts           (Metro asset map per kind)
//
// VD_SYSTEM_MANIFEST merges into the cell manifest by spreading `cells` — the same CellManifest type, so
// configureVdCellSource can serve these packs through the same hash-pinned path as the geometry cells.
//
//   node tooling/city/vd-port/write-systems-manifest.mjs            # emit + pin
//   node tooling/city/vd-port/write-systems-manifest.mjs --pins     # pin what's on disk, no re-emit
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MANIFEST_OUT, OUT, cellSort } from './vd-game-cells.mjs';
import { writeColliderCells } from './write-colliders.mjs';
import { writePedCells } from './write-pednet.mjs';
import { writeTrafficCells } from './write-traffic.mjs';
import { writeSpawnCells } from './write-spawns.mjs';
import { writeLabelCells } from './write-labels.mjs';

const HERE = fileURLToPath(new URL('.', import.meta.url));
const KINDS = ['colliders', 'pednet', 'traffic', 'spawns', 'labels'];

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

export async function writeSystemsManifest({ out = OUT, manifestOut = MANIFEST_OUT, emit = true } = {}) {
  if (emit) {
    for (const run of [writeColliderCells, writePedCells, writeTrafficCells, writeSpawnCells, writeLabelCells]) {
      await run({ out });
    }
  }

  const cells = {};
  const assets = {};
  let totalBytes = 0;
  for (const kind of KINDS) {
    const dir = join(out, kind);
    let files = [];
    try {
      files = readdirSync(dir).filter((n) => n.endsWith('.bin'));
    } catch {
      continue; // a kind that emitted nothing has no dir
    }
    assets[kind] = [];
    for (const f of files.sort(cellSort)) {
      const key = `${kind}/${f.slice(0, -4)}`;
      const buf = readFileSync(join(dir, f));
      cells[key] = { path: `${key}.bin`, sha256: sha256(buf), bytes: buf.length, bundled: true };
      assets[kind].push(f.slice(0, -4));
      totalBytes += buf.length;
    }
  }

  const lines = Object.keys(cells).sort().map((k) => {
    const c = cells[k];
    return `    '${k}': { path: '${c.path}', sha256: '${c.sha256}', bytes: ${c.bytes}, bundled: ${c.bundled} },`;
  });
  const ts = `// GENERATED by tooling/city/vd-port/write-systems-manifest.mjs (sha256 + byteLength of every game-system cell pack). Do not edit by hand.
// The manifest the on-demand source pins the Phase 4 packs against (cell-source.ts): colliders, the
// pedestrian network, the lane-level traffic graph, mon spawn zones and street labels, all keyed to the
// 128 m streamer cell grid. Merge into the cell manifest by spreading \`cells\` over VD_CELL_MANIFEST's.
import type { CellManifest } from '../types.ts';

export const VD_SYSTEM_MANIFEST: CellManifest = {
  version: 1,
  cells: {
${lines.join('\n')}
  },
};
`;
  await mkdir(join(manifestOut, '..'), { recursive: true });
  await writeFile(manifestOut, ts);

  const assetsTs = [
    '// GENERATED by tooling/city/vd-port/write-systems-manifest.mjs. Metro registers .bin as an asset',
    '// (apps/mobile/metro.config.js), so require() gives an asset id @acme/ui/three/asset-bytes resolves —',
    '// the bundled copy the cell source prefers for these packs (all `bundled: true` above).',
    '/* eslint-disable @typescript-eslint/no-require-imports */',
    'export const VD_SYSTEM_ASSETS: Readonly<Record<string, Readonly<Record<string, number>>>> = {',
    ...KINDS.filter((k) => assets[k]?.length).map(
      (k) => `  ${k}: {\n${assets[k].map((cell) => `    '${cell}': require('./${k}/${cell}.bin'),`).join('\n')}\n  },`,
    ),
    '};',
    '',
  ].join('\n');
  await mkdir(out, { recursive: true });
  await writeFile(join(out, 'assets.ts'), assetsTs);

  const counts = Object.fromEntries(KINDS.map((k) => [k, assets[k]?.length ?? 0]));
  console.log(`systems manifest: ${lines.length} cells (${(totalBytes / 1e6).toFixed(1)} MB) -> ${manifestOut}`);
  console.log(`  ${KINDS.map((k) => `${k} ${counts[k]}`).join(', ')}`);
  return { cells, counts };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  await writeSystemsManifest({ emit: !process.argv.includes('--pins') });
}
