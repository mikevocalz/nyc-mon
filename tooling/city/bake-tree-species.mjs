// Bakes each census tree's species and trunk size into
// packages/app/features/game/world/vd-tree-species.ts, aligned with the
// tile's trees.census order. Valdrada compiles them from the 2015 Street Tree
// Census (spc_common, tree_dbh) into its TREE records as p0 = species id and
// p1 = dbh in inches (client/tools/pipeline/compile.mjs ~L4517-4527). The tile
// already holds the positions; this matches each to its record by position.
//
// Run after build.mjs: node tooling/city/bake-tree-species.mjs
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { decodeTile, FURN } from './valdrada/decode.mjs';

const ROOT = dirname(fileURLToPath(import.meta.url));
const VD_DIR = join(ROOT, '.cache/valdrada');
const TILE = join(ROOT, '../../packages/app/features/game/data/harlem-apollo.json');
const OUT = join(ROOT, '../../packages/app/features/game/world/vd-tree-species.ts');
const round = (v) => Math.round(v * 10) / 10;

const records = new Map();
for (const f of (await readdir(VD_DIR)).filter((n) => n.endsWith('.bin')).sort()) {
  const buf = await readFile(join(VD_DIR, f));
  const tile = decodeTile(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
  for (const r of tile.furniture) {
    if (r.k !== FURN.TREE || r.p2 !== 1) continue;
    records.set(`${round(r.x)},${round(r.z)}`, [r.p0 & 255, Math.min(255, r.p1)]);
  }
}
const census = JSON.parse(await readFile(TILE, 'utf8')).trees.census;
const n = census.length / 2;
const species = new Uint8Array(n);
const dbh = new Uint8Array(n);
let matched = 0;
for (let i = 0; i < n; i++) {
  const hit = records.get(`${census[i * 2]},${census[i * 2 + 1]}`);
  if (hit) { [species[i], dbh[i]] = hit; matched++; }
}
const counts = {};
for (const s of species) counts[s] = (counts[s] ?? 0) + 1;
const text = [
  '// Generated by tooling/city/bake-tree-species.mjs. Do not edit.',
  '// Species id and trunk diameter (inches) per trees.census entry, from the 2015 NYC Street',
  '// Tree Census as Valdrada v0.4.0 compiled it (compile.mjs: 1 plane, 2 honeylocust, 3 pear,',
  '// 4 ginkgo, 5 oak, 6 linden, 7 maple, 8 cherry, 9 sophora, 10 zelkova, 11 ash, 12 elm; 0 unknown).',
  `export const VD_CENSUS_SPECIES = ${JSON.stringify(Buffer.from(species).toString('base64'))};`,
  `export const VD_CENSUS_DBH = ${JSON.stringify(Buffer.from(dbh).toString('base64'))};`,
  '',
].join('\n');
await writeFile(OUT, text);
console.log(`census ${n}, matched ${matched}; species counts`, counts);
