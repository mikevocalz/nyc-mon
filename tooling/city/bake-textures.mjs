// Bakes the Valdrada surface textures the "vd" material lane samples into
// packages/app/features/game/world/vd-textures.ts. Same reason as
// bake-foliage.mjs: react-native-webgpu has no image decoder, so the pixels
// ship as data and become DataTextures at runtime.
//
// Source: Valdrada v0.4.0 Content/textures on Hugging Face
// (mehmetkeremturkcan/valdrada, revision v0.4.0). Valdrada's LICENSING.md
// lists the textures as CC0. Fetch them first:
//   for f in <names below>; do curl -sSL -o tooling/city/.cache/vd-textures/$f.jpg \
//     https://huggingface.co/datasets/mehmetkeremturkcan/valdrada/resolve/v0.4.0/Content/textures/$f.jpg; done
//
// Decoding uses macOS `sips` (JPEG -> 24-bit BMP), so this script runs on a Mac.
// Colour maps keep RGB; normal maps keep the tangent-space X and Y (Z is
// rebuilt in the shader).
//
// Run: node tooling/city/bake-textures.mjs
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, '.cache/vd-textures');
const OUT = join(ROOT, '../../packages/app/features/game/world/vd-textures.ts');
// ponytail: 256 px per map keeps the baked module near 2.6 MB of base64 in the JS bundle.
// Move to asset files plus a native decoder if the maps need to go sharper.
const SIZE = 256;

// Order is the array layer the shader indexes; vd-materials.ts mirrors it.
const WALLS = ['wall_brownbrick', 'wall_redbrick', 'wall_whitebrick', 'wall_stone', 'wall_plaster'];
const GROUND = ['asphalt_col', 'paving_col', 'concrete_col'];
const NORMALS = ['brick_nrm', 'asphalt_nrm', 'paving_nrm'];

const tmp = mkdtempSync(join(tmpdir(), 'vd-bake-'));
function decode(name) {
  const bmp = join(tmp, `${name}.bmp`);
  execFileSync('sips', ['-s', 'format', 'bmp', '-z', String(SIZE), String(SIZE), join(SRC, `${name}.jpg`), '--out', bmp], { stdio: 'ignore' });
  const b = readFileSync(bmp);
  if (b.toString('latin1', 0, 2) !== 'BM') throw new Error(`${name}: not a BMP`);
  const offset = b.readUInt32LE(10);
  const width = b.readInt32LE(18);
  const height = b.readInt32LE(22);
  const bpp = b.readUInt16LE(28);
  if (width !== SIZE || Math.abs(height) !== SIZE || bpp !== 24) throw new Error(`${name}: ${width}x${height}@${bpp}, expected ${SIZE}x${SIZE}@24`);
  const stride = Math.ceil((width * 3) / 4) * 4;
  const rgb = Buffer.alloc(SIZE * SIZE * 3);
  for (let y = 0; y < SIZE; y++) {
    // Negative height means rows are stored top-down.
    const row = height < 0 ? y : SIZE - 1 - y;
    for (let x = 0; x < SIZE; x++) {
      const s = offset + row * stride + x * 3;
      const d = (y * SIZE + x) * 3;
      rgb[d] = b[s + 2]; rgb[d + 1] = b[s + 1]; rgb[d + 2] = b[s];
    }
  }
  return rgb;
}
const xy = (rgb) => {
  const out = Buffer.alloc(SIZE * SIZE * 2);
  for (let i = 0; i < SIZE * SIZE; i++) { out[i * 2] = rgb[i * 3]; out[i * 2 + 1] = rgb[i * 3 + 1]; }
  return out;
};

// Per-layer mean colour 0..1: the shader divides each sample by it, the way
// Valdrada's facade divides by its wallM constants, so the photo adds grain
// around the wall's own tone instead of replacing it.
const mean = (rgb) => {
  const sum = [0, 0, 0];
  for (let i = 0; i < rgb.length; i += 3) { sum[0] += rgb[i]; sum[1] += rgb[i + 1]; sum[2] += rgb[i + 2]; }
  return sum.map((s) => Number((s / (rgb.length / 3) / 255).toFixed(4)));
};
const wallMaps = WALLS.map(decode);
const groundMaps = GROUND.map(decode);
const walls = Buffer.concat(wallMaps);
const ground = Buffer.concat(groundMaps);
const normals = Buffer.concat(NORMALS.map((n) => xy(decode(n))));
rmSync(tmp, { recursive: true });

const text = [
  '// Generated by tooling/city/bake-textures.mjs. Do not edit.',
  '// Surface textures from Valdrada v0.4.0 (github.com/mkturkcan/valdrada, Hugging Face',
  '// mehmetkeremturkcan/valdrada Content/textures). CC0-1.0 per Valdrada LICENSING.md.',
  `export const VD_TEXTURE_SIZE = ${SIZE};`,
  `export const VD_WALL_LAYERS = ${JSON.stringify(WALLS)} as const;`,
  `export const VD_GROUND_LAYERS = ${JSON.stringify(GROUND)} as const;`,
  `export const VD_NORMAL_LAYERS = ${JSON.stringify(NORMALS)} as const;`,
  `export const VD_WALL_MEANS = ${JSON.stringify(wallMaps.map(mean))} as const;`,
  `export const VD_GROUND_MEANS = ${JSON.stringify(groundMaps.map(mean))} as const;`,
  '/** RGB, layer-major, rows top-down. */',
  `export const VD_WALLS_RGB = ${JSON.stringify(walls.toString('base64'))};`,
  '/** RGB, layer-major, rows top-down. */',
  `export const VD_GROUND_RGB = ${JSON.stringify(ground.toString('base64'))};`,
  '/** Tangent-space normal X,Y (0..255 → -1..1), layer-major. */',
  `export const VD_NORMALS_XY = ${JSON.stringify(normals.toString('base64'))};`,
  '',
].join('\n');
writeFileSync(OUT, text);
console.log(`wrote ${OUT} (${(text.length / 1024 / 1024).toFixed(2)} MB)`);
