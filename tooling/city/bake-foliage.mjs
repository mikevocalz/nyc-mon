// Bakes the leaf-card alpha the city's tree crowns cut out, into
// packages/app/features/game/world/leaf-alpha.ts, so no image decoder runs at
// runtime (react-native-webgpu has none). A TS module rather than JSON: node
// tests would need an import attribute for JSON, which Metro does not parse.
//
// Source: the Quaternius "Ultimate Stylized Nature" leaf texture (CC0), as
// baked by vg-demos-all scripts/foliage/build.mjs into
// src/demos/metro-live/data/foliage.json (MIT repo; the texture itself is CC0).
// Only the alpha channel is kept: crown colour comes from the instance colour.
//
// Run: node tooling/city/bake-foliage.mjs [path/to/vg-demos-all]
import { readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(fileURLToPath(import.meta.url));
const REPO = process.argv[2] ?? join(homedir(), 'Downloads/vg-demos-all');
const SOURCE = join(REPO, 'src/demos/metro-live/data/foliage.json');
const OUT = join(ROOT, '../../packages/app/features/game/world/leaf-alpha.ts');

const foliage = JSON.parse(await readFile(SOURCE, 'utf8'));
const { w, h, rgba } = foliage.textures.leaf;
const bytes = Buffer.from(rgba, 'base64');
if (bytes.length !== w * h * 4) throw new Error(`Leaf texture is ${bytes.length} bytes, expected ${w * h * 4}`);
const alpha = Buffer.alloc(w * h);
for (let i = 0; i < w * h; i++) alpha[i] = bytes[i * 4 + 3];

const out = {
  attribution: 'Leaf texture from the Ultimate Stylized Nature pack by Quaternius (quaternius.com)',
  license: 'CC0-1.0',
  source: 'https://poly.pizza/bundle/Ultimate-Stylized-Nature-Pack-zyIyYd9yGr',
  width: w,
  height: h,
  alpha: alpha.toString('base64'),
};
const text = [
  '// Generated by tooling/city/bake-foliage.mjs. Do not edit.',
  `// ${out.attribution}. ${out.license}: ${out.source}`,
  `export const LEAF_ALPHA = ${JSON.stringify({ width: out.width, height: out.height, alpha: out.alpha })} as const;`,
  '',
].join('\n');
await writeFile(OUT, text);
console.log(`leaf alpha ${w}x${h} -> ${OUT} (${(text.length / 1024).toFixed(1)} KB)`);
